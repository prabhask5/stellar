// Regenerates src/types.ts from a running database through pg-meta.
// Usage: pnpm stack:up && pnpm --filter @stellar/db migrate && pnpm --filter @stellar/db gen-types
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const url = process.env.SUPABASE_URL ?? "http://127.0.0.1:54321";
const key = process.env.SUPABASE_SERVICE_ROLE_KEY;
if (!key) {
  console.error("Set SUPABASE_SERVICE_ROLE_KEY (see dev/supabase/dev.env).");
  process.exit(1);
}
const res = await fetch(`${url}/pg/generators/typescript?included_schemas=public`, {
  headers: { apikey: key, Authorization: `Bearer ${key}` },
});
if (!res.ok) {
  console.error(`pg-meta answered ${res.status}: ${await res.text()}`);
  process.exit(1);
}
const body = await res.text();
const out = resolve(dirname(fileURLToPath(import.meta.url)), "../src/types.ts");
writeFileSync(
  out,
  `// Generated by packages/db/scripts/gen-types.ts (pg-meta). Do not edit by hand.\n${body}`,
);
console.info(`wrote ${out}`);
